ALTER PROCEDURE [dbo].[Acc_DynamicCustomerInfo_09]
	@Custid INT
	--,@roleid TINYINT
	--,@srecommend INT
	--,@mrecommend INT	
	--,@Mode BIT = 0
	, @maxcustid INT
	,@target VARCHAR(20)
AS
BEGIN
	SET NOCOUNT ON
	
	IF (@target = 'REPLICATED' AND @@SERVERNAME = 'DBCUST') RETURN	-- run at all replicated servers
	IF (@target = 'DBCUST' AND @@SERVERNAME <> 'DBCUST') RETURN -- run at dbtrans only
	
	IF NOT (dbo.f_CheckRepTable('Custinfo') = 1 
	   AND dbo.f_CheckRepTable('CustProductStatus') = 1
	   AND dbo.f_CheckRepTable('ProductSettingDetail') = 1
	   AND dbo.f_CheckRepTable('ProductStatusProfile') = 1
	   )
		RETURN
	
	
	/*******************************CUST PRODUCT STATUS TABLE*******************************/	
	
	CREATE TABLE #tmpCust (Custid INT PRIMARY KEY)
	
	INSERT INTO #tmpCust (Custid)
	SELECT Custid
	FROM custInfo WITH (NOLOCK)
	WHERE srecommend = @Custid AND roleid IN (1,2,3) AND mrecommend <> 23018473 AND custid <= @maxcustid
	
	UPDATE cs
		SET bitmapIsDisabled = dbo.f_GenerateProductStatus(bitmapIsDisabled, 7, 1) 
	FROM [dbo].[CustProductStatus] cs WITH(UPDLOCK)
		INNER JOIN #tmpCust T ON CS.CustID = T.Custid 
	
END
