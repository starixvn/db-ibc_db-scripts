DECLARE @CustID INT, @i INT = 1, @Max INT, @ErrCode INT, @ErrMsg NVARCHAR(1000) 
SELECT @Max = MAX(ID) FROM #SuperList
 
WHILE @i <= @Max
BEGIN 
		
	SELECT @CustID = CustID FROM #SuperList WHERE ID = @i

	EXEC [Acc_CustGroupUpdPrimaryExtraPTGroup]
		@CustID			 = @CustID,
		@GroupName		 = 'ACCUT',
		@EffectiveDate	 = '20200606',
		@UserID			= 10278938,   ----starixIT 
		@IP				= '',
		@ErrCode		= @ErrCode  OUTPUT,
		@ErrMsg			= @ErrMsg OUTPUT

	SELECT @i = @i+1
 
 END