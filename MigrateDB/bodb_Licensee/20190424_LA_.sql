/* 9.*/
ALTER TABLE LA_InvoiceSetting
	ADD InvSettingId INT NULL
GO

;WITH CTE AS
(
	SELECT FromPartyId,ToPartyId,ProductId,InvTypeId,ROW_NUMBER() OVER(ORDER BY (SELECT NULL)) AS RN
	FROM LA_InvoiceSetting WITH (NOLOCK)
)
UPDATE l WITH (ROWLOCK, UPDLOCK)
SET l.InvSettingId = c.RN
FROM dbo.LA_InvoiceSetting l
	INNER JOIN CTE c
		ON l.FromPartyId = c.FromPartyId
			AND l.ToPartyId = c.ToPartyId
			AND l.InvTypeId = c.InvTypeId
			AND (
				(l.ProductId IS NULL AND c.ProductId IS NULL)
				OR l.ProductId = c.ProductId
			)
GO

ALTER TABLE LA_InvoiceSetting
	ALTER COLUMN InvSettingId INT NOT NULL
GO

