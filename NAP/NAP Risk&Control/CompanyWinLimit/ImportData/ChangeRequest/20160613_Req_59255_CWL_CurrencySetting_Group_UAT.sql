INSERT INTO dbo.Winlimit_GameGroupSetting_UAT (ProductID, BetTypeID, GroupID)
SELECT DISTINCT t.ProductID, t.BetTypeID, t.GroupID,tmp.BetTypeRefID
FROM #Temp T
	CROSS APPLY (SELECT MIN(BetTypeID) AS BetTypeRefID
				 FROM #Temp T1 WHERE T1.ProductID = T.ProductID
				 )Tmp

INSERT INTO WinLimit_ProductSettingDetail_UAT (ProductID, GroupID, ExchangeID, SiteID, LevelID,  IsBlockedPlaceBet, IsBlockedTransfer, MaxWinLimit_RM)
SELECT DISTINCT ProductID, GroupID, ExchangeID, s.SiteID, 1, 0, 0,t.Level1 MaxWinLimit_RM
FROM #Temp t
	CROSS JOIN EXCHANGE E (NOLOCK) 
	CROSS JOIN (SELECT siteid FROM Site WITH (NOLOCK) WHERE isActive = 1) AS S

UNION ALL
SELECT DISTINCT ProductID, GroupID, ExchangeID, s.SiteID, 2, 0, 0,t.Level2 MaxWinLimit_RM
FROM #Temp t
	CROSS JOIN EXCHANGE E (NOLOCK) 
	CROSS JOIN (SELECT siteid FROM Site WITH (NOLOCK) WHERE isActive = 1) AS S
	
UNION ALL
SELECT DISTINCT ProductID, GroupID, ExchangeID, s.SiteID, 3, 0, 0,t.Level3 MaxWinLimit_RM
FROM #Temp t
	CROSS JOIN EXCHANGE E (NOLOCK) 
	CROSS JOIN (SELECT siteid FROM Site WITH (NOLOCK) WHERE isActive = 1) AS S	


INSERT INTO winlimit_productsetting_UAT (ProductID,BettypeID,LevelID,SettingStatus)
SELECT DISTINCT ProductID,MIN(BettypeID),T.LevelID,0
FROM #Temp t1
	CROSS JOIN (SELECT LEVELID FROM winlimit_levelSetting_UAT WITH (NOLOCK)) AS T
WHERE NOT EXISTS (SELECT 1 FROM winlimit_productsetting_UAT t2 (nolock) WHERE T1.ProductID = T2.ProductID)
GROUP BY ProductID,T.LevelID


